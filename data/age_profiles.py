"""按实际年龄提供的班主任提醒。"""

AGE_GROUPS = [
    (6, 8, "6～8 岁", "这一年龄阶段更需要清晰、稳定、具体的规则和反馈。班主任可多使用可视化任务、即时鼓励和固定班级流程，减少过长、抽象的说教。"),
    (9, 11, "9～11 岁", "这一阶段的学生开始更加关注同伴评价。反馈尽量具体到行为和努力，避免把学生简单贴上固定标签。"),
    (12, 14, "12～14 岁", "这一阶段学生对尊重、公平和同伴评价通常更加敏感。出现冲突或情绪问题时，优先私下沟通，关注持续性行为变化，同时保护学生隐私。"),
    (15, 18, "15～18 岁", "这一阶段应逐步从替学生决定转向帮助学生做决定。在明确底线和规则的同时，给予学生更多参与选择、表达观点和承担结果的机会。"),
    (19, 120, "19 岁以上", "以成人式沟通为主，强调自主选择、责任和资源支持，避免过度替代学生做决定。"),
]

def get_age_profile(age: int) -> tuple[str, str]:
    for low, high, label, tip in AGE_GROUPS:
        if low <= age <= high:
            return label, tip
    return "6 岁以下", "请结合学生的实际发展情况提供适龄支持，并以真实观察和沟通为依据。"
